"""Fixed-template explanations, limitation statements and the article summary statement (SPEC S-12.2, S-7.7; Step 10).

Every sentence here is a fixed template filled with values read from the committed report graph: a claim's class,
rule, table version, reasons, evidence counts, evidence-set digest and unit anchor; the summary counts; the identities.
No sentence is written freely, nothing is generated by a model, nothing is read from the network, and the output is a
pure function of its input, so equal inputs give byte-identical text.

Wording rules (owner Step 10 items 9, 11 and 32; SPEC S-1.1, S-7.5, S-7.7):

- a not-found claim says only "No matching record was found in the checked sources." and names the checked sources;
- a notice claim says that the cited identifier resolves to a notice; it never attaches a status to the work;
- an unavailable lookup says that the lookup was unavailable and states no result;
- an identity conflict says that the identifiers conflict and require resolution;
- no template says that a work or an article is "clean", "safe" or "not retracted", or that an article has "no
  retracted citations" (``FORBIDDEN`` lists the phrases a test checks every template against).

Kinds (``KIND``) keep the seven distinctions the owner named apart: finding, not found, notice, unresolved (identity,
identifier or status), contradiction (identity conflict or source contradiction), unavailable and out of scope.
"""

