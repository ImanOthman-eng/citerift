def _keys(keys: Iterable[Mapping[str, str]]) -> str:
    out = [f"{k['scheme'].upper()} {k['normalized']}" for k in keys]
    return ", ".join(out) if out else "no identifier"


def _sources(sources: Iterable[Mapping[str, Any]]) -> str:
    out = [f"{s['source_id']} ({s.get('source_version') or 'version not stated'})" for s in sources]
    return "; ".join(out) if out else "none recorded"


def _alternatives(alts: Iterable[Mapping[str, Any]]) -> str:
    values = [str(a["value"]) if not isinstance(a["value"], Mapping) else "an identity" for a in alts]
    return ", ".join(values) if values else "no alternative recorded"


def claim_explanation(entry: Mapping[str, Any]) -> dict[str, Any]:
    """The explanation of one claim entry of the report (``report#/$defs/claim_entry``)."""
    claim = entry["claim"]
    cls = claim["class"]
    kind = KIND[cls]
    template = "unresolved_coverage" if cls == "UNRESOLVED_STATUS" and claim["rule"] == "D-12" else kind
    text = CLAIM_TEMPLATES[template].format(
        event=_FINDING.get(cls, ""),
        sources=_sources(entry["checked_sources"]),
        alternatives=_alternatives(claim["alternatives"]),
        scope=_SCOPE.get(cls, ""),
    )
    reasons = [{"code": r, "text": REASON_TEXT[r]} for r in claim["reasons"]]
    unit = entry["unit"]
    chain = (
        f"Rule {claim['rule']} of decision table {claim['table_version']}; class {cls}; "
        f"identifiers: {_keys(claim['candidate']['keys'])}; "
        f"evidence: {claim['supporting_count']} supporting, {claim['contradicting_count']} contradicting "
        f"(evidence set {claim['evidence_set']}); unit {unit['unit_id']} bytes {unit['byte_start']}-{unit['byte_end']} "
        f"(span sha256 {unit['unit_span_sha256']})."
    )
    if reasons:
        chain += " Reasons: " + "; ".join(f"{r['code']}: {r['text']}" for r in reasons) + "."
    question = entry["question"]
    if question is not None:
        chain += f" Open question {question['question_id']} ({question['kind']})."
    return {
        "claim_id": claim["claim_id"],
        "class": cls,
        "kind": kind,
        "rule": claim["rule"],
        "disposition": entry["decision"]["disposition"],
        "text": text,
        "chain": chain,
        "reasons": reasons,
    }


