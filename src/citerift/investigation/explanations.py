def _counts(claims: Iterable[Mapping[str, Any]]) -> dict[str, int]:
    out = dict.fromkeys(
        (
            "lookup_unavailable",
            "budget_refused",
            "identity_conflict",
            "source_contradiction",
            "unresolved_identity",
            "unresolved_identifier",
            "unresolved_status",
            "notice",
            "out_of_scope",
        ),
        0,
    )
    for c in claims:
        kind = KIND[c["class"]]
        if kind == "unavailable":
            out["lookup_unavailable"] += 1
            out["budget_refused"] += "LOOKUP_EVIDENCE_LIMIT_EXCEEDED" in c["reasons"]
        elif kind in out:
            out[kind] += 1
    return out


def limitations(manifest: Mapping[str, Any], claims: Iterable[Mapping[str, Any]]) -> list[dict[str, str]]:
    """The limitation statements of a report: ``{code, text}`` in the fixed order of ``LIMITATION_TEMPLATES``.
    ``claims`` are the claim payloads of the claims component."""
    stored = set(manifest["limitations"])
    counts = _counts(claims)
    values = {
        **counts,
        "snapshot_id": manifest["article_summary"]["snapshot_id"],
        "open_questions": manifest["article_summary"]["open_questions"],
        "budget": manifest["identities"]["config"]["lookup_evidence_budget_bytes"],
    }
    present = {
        "CHECKED_SOURCES_ONLY": "CHECKED_SOURCES_ONLY" in stored,
        "SNAPSHOT_COVERAGE": True,
        "EXTRACTION_PARTIAL": "EXTRACTION_PARTIAL" in stored,
        "LOOKUP_UNAVAILABLE_FOR_SOME_CANDIDATES": counts["lookup_unavailable"] > 0,
        "LOOKUP_EVIDENCE_BUDGET_REFUSED": counts["budget_refused"] > 0,
        "IDENTITY_CONFLICTS": counts["identity_conflict"] > 0,
        "SOURCE_CONTRADICTIONS": counts["source_contradiction"] > 0,
        "UNRESOLVED_IDENTITY": counts["unresolved_identity"] > 0,
        "UNRESOLVED_IDENTIFIER": counts["unresolved_identifier"] > 0,
        "UNRESOLVED_STATUS": counts["unresolved_status"] > 0,
        "NOTICE_CITATIONS": counts["notice"] > 0,
        "OPEN_QUESTIONS": manifest["article_summary"]["open_questions"] > 0,
        "OUT_OF_SCOPE_UNITS": counts["out_of_scope"] > 0,
        "MARKERS_NOT_INTERPRETED": "MARKERS_NOT_INTERPRETED" in stored,
        "OBSERVATION_ROLE_IDENTIFIERS_NOT_DECIDED": "OBSERVATION_ROLE_IDENTIFIERS_NOT_DECIDED" in stored,
        "UNSTRUCTURED_TEXT_AS_STAGE03_DEFINES": "UNSTRUCTURED_TEXT_AS_STAGE03_DEFINES" in stored,
    }
    return [{"code": code, "text": t.format(**values)} for code, t in LIMITATION_TEMPLATES.items() if present[code]]


def summary_statement(manifest: Mapping[str, Any], positive_work_count: int) -> str:
    """S-7.7: counts by class, open questions and the snapshot id; the scoped not-found sentence only when every
    in-scope claim is ``NOT_FOUND_IN_CHECKED_SOURCES``. Nothing is said about the article from absent claims."""
    s = manifest["article_summary"]
    by_class = s["claims_by_class"]
    parts = [f"{c}: {n}" for c, n in sorted(by_class.items())]
    text = (
        f"Claims by class: {', '.join(parts) if parts else 'none'}. Open questions: {s['open_questions']}. "
        f"Retraction Watch snapshot: {s['snapshot_id']}. Distinct works with a positive claim: {positive_work_count}."
    )
    in_scope = {c: n for c, n in by_class.items() if c not in OUT_OF_SCOPE}
    if in_scope and set(in_scope) == {"NOT_FOUND_IN_CHECKED_SOURCES"}:
        n = in_scope["NOT_FOUND_IN_CHECKED_SOURCES"]
        text += (
            f" For the {n} candidate identifier(s) listed, no matching record was found in the checked sources "
            f"(snapshot {s['snapshot_id']})."
        )
    return text
