"""Source/render reconciliation (SPECIFICATION.md 12.3).

The source model and the render capture are joined only through structure the render itself declares:

* reference uses are matched within three groups that the render keeps apart: uses in article text, uses produced
  inside template output (a ref in a template parameter, or a ref generated by a template), and uses nested in
  another reference's text;
* in article text the two sequences are aligned at anchors (named uses whose name occurs equally often on both
  sides); between anchors a segment is matched position by position only when both sides have the same length and
  every pair is compatible; any other segment is left unmatched and reported, never guessed;
* template output is joined to the source template whose canonical name and parameter values equal those in the
  render's ``data-mw``;
* a container is matched to the reference list item its matched uses point to, and only when they all point to one;
* a citation unit is matched to a template output inside that item by the same template key.

An identifier occurrence is confirmed in the render when an identifier link inside the matched region decodes to the
same scheme and normalized value. Links that no source occurrence explains are listed as render-only.
"""

from __future__ import annotations

import bisect
import html
import re
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Any

from citerift.wiki.identifiers import decode_render_href
from citerift.wiki.issues import Issue
from citerift.wiki.model import SourceModel, Use
from citerift.wiki.profile import Profile, WikiProfile
from citerift.wiki.render import RenderDoc, RenderLink, RenderTransclusion, RenderUse
from citerift.wiki.source import TemplateRecord

TemplateKey = tuple[str, tuple[tuple[str, str], ...]]
_URL_IN_TEXT = re.compile(r"(?i)(?:https?:)?//[^\s|\[\]{}<>\"']+")


@dataclass
class Reconciliation:
    use_match: dict[str, int] = field(default_factory=dict)  # source use id -> render use index
    use_state: dict[str, str] = field(default_factory=dict)
    use_basis: dict[str, str] = field(default_factory=dict)
    render_use_matched: set[int] = field(default_factory=set)
    container_note: dict[str, str] = field(default_factory=dict)  # container id -> note id or list item path
    container_state: dict[str, str] = field(default_factory=dict)
    unit_transclusion: dict[str, str] = field(default_factory=dict)  # unit id -> about
    unit_state: dict[str, str] = field(default_factory=dict)
    template_about: dict[int, tuple[str, int]] = field(default_factory=dict)  # source template -> (about, part)
    witnesses: dict[str, list[int]] = field(default_factory=dict)  # occurrence id -> render link indexes
    witness_state: dict[str, str] = field(default_factory=dict)
    render_only_links: list[dict[str, Any]] = field(default_factory=list)
    unmatched_render_uses: list[int] = field(default_factory=list)
    issues: list[Issue] = field(default_factory=list)
    segments: Counter[str] = field(default_factory=Counter)


def _canon_target(wiki: WikiProfile, raw: str) -> str:
    stripped = raw.strip()
    if stripped.startswith("#") or stripped.casefold().startswith(("subst:", "safesubst:")):
        return stripped.casefold()
    canon = wiki.canonical_template(stripped)
    return canon if canon is not None else stripped


def source_template_key(t: TemplateRecord, text: str, wiki: WikiProfile) -> TemplateKey:
    params: dict[str, str] = {}
    for p in t.params:
        params[p.name] = text[p.value_start : p.value_end].strip()
    return _canon_target(wiki, t.raw_name), tuple(sorted(params.items()))


def render_template_key(target: str, params: dict[str, str], wiki: WikiProfile) -> TemplateKey:
    return _canon_target(wiki, target), tuple(sorted((k.strip(), v.strip()) for k, v in params.items()))


def _compatible(u: Use, r: RenderUse) -> bool:
    """Name and group of a source use agree with the render's data-mw (both trimmed, entities decoded)."""
    if not r.data_mw_ok:
        return False
    r_group = html.unescape(r.group).strip()
    r_name = html.unescape(r.name).strip() if r.name is not None else None
    if r_name == "":
        r_name = None
    if u.origin in ("tag",):
        return u.group == r_group and u.name == r_name
    # Template-generated uses: the generating template decides name and group; only a stated name must agree.
    return u.name is None or r_name is None or u.name == r_name


def _key(u: Use) -> tuple[str, str] | None:
    return (u.group, u.name) if u.name is not None else None


class Reconciler:
    def __init__(self, model: SourceModel, render: RenderDoc, wiki: WikiProfile, profile: Profile) -> None:
        self.m = model
        self.r = render
        self.wiki = wiki
        self.profile = profile
        self.out = Reconciliation()
        self.text = ""
        self._url_cache: dict[str, frozenset[str]] = {}
        self._container_by_id = {c.id: c for c in model.containers}
        self._links_by: dict[tuple[str, str], list[RenderLink]] = {}
        for x in render.links:
            for kind, value in (("note", x.in_note), ("item", x.in_list_item), ("about", x.in_transclusion)):
                if value is not None:
                    self._links_by.setdefault((kind, value), []).append(x)
        # Content keys of a rendered note: its link targets, plus "id:<scheme>:<key>" for every identifier link the
        # note shows (decoded and normalized as source identifiers are).
        hrefs: dict[str, set[str]] = {}
        for link in render.links:
            if link.in_note is not None:
                keys = hrefs.setdefault(link.in_note, set())
                keys.add(link.href)
                got = decode_render_href(link.href)
                if got is not None and got[1].normalized.valid:
                    keys.add(f"id:{got[0]}:{got[1].normalized.normalized}")
        self.note_hrefs = {k: frozenset(v) for k, v in hrefs.items()}
        self._container_ids: dict[str, set[str]] = {}
        for o in model.occurrences:
            if (
                o.container_id is not None
                and o.role in ("primary_citation_field", "identifier_link")
                and o.decoded is not None
                and o.decoded.normalized.valid
            ):
                key = f"id:{o.cand.scheme}:{o.decoded.normalized.normalized}"
                self._container_ids.setdefault(o.container_id, set()).add(key)
        # Cite numbers the notes of one list in the order of first use; the render order of first uses must agree.
        self._note_rank = {n.note_id: (n.list_index, n.index) for n in render.notes}
        self._duplicate_notes = set(render.duplicate_ids)
        self._last_rank: dict[int, int] = {}
        self._first_use: dict[str, int] = {}
        for u in model.uses:
            if u.container_id is not None:
                self._first_use[u.container_id] = min(u.start, self._first_use.get(u.container_id, u.start))
        self.omitted = {t.about for t in render.transclusions if t.omitted}
        self.omitted_notes = {
            t.in_note or t.in_list_item for t in render.transclusions if t.omitted and (t.in_note or t.in_list_item)
        }

    # Uses ---------------------------------------------------------------------------------------------------

    def _pair(self, u: Use, r: RenderUse, basis: str) -> None:
        self.out.use_match[u.id] = r.index
        self.out.use_state[u.id] = "matched"
        self.out.use_basis[u.id] = basis
        self.out.render_use_matched.add(r.index)

    def _source_urls(self, u: Use) -> frozenset[str]:
        if u.container_id is None:
            return frozenset()
        if u.container_id not in self._url_cache:
            c = self._container_by_id[u.container_id]
            urls = {html.unescape(x) for d in c.definitions for x in _URL_IN_TEXT.findall(d["body_text"])}
            urls |= self._container_ids.get(u.container_id, set())
            self._url_cache[u.container_id] = frozenset(urls)
        return self._url_cache[u.container_id]

    def _content_pair(self, src: Sequence[Use], ren: Sequence[RenderUse]) -> list[Use]:
        """Second chance for uses that structure could not pair: a source use and a render use pair when the
        reference text of each contains an external URL or a normalized DOI or PMID of the other and no other
        candidate on either side does. Returns the source uses that stay unpaired."""
        free = [r for r in ren if r.index not in self.out.render_use_matched]
        cand: dict[str, list[RenderUse]] = {}
        back: dict[int, list[str]] = {}
        for u in src:
            urls = self._source_urls(u)
            if not urls:
                continue
            for r in free:
                if (
                    r.target_note is not None
                    and urls & self.note_hrefs.get(r.target_note, frozenset())
                    and _compatible(u, r)
                ):
                    cand.setdefault(u.id, []).append(r)
                    back.setdefault(r.index, []).append(u.id)
        left = []
        for u in src:
            rs = cand.get(u.id, [])
            if len(rs) == 1 and back[rs[0].index] == [u.id]:
                shared = self._source_urls(u) & self.note_hrefs.get(rs[0].target_note or "", frozenset())
                by_url = any(not k.startswith("id:") for k in shared)
                self._pair(
                    u, rs[0], "unique_url_in_reference_text" if by_url else "unique_identifier_in_reference_text"
                )
            else:
                left.append(u)
        return left

    def _numbering_agrees(self, src: Sequence[Use], ren: Sequence[RenderUse]) -> bool:
        """Position pairs are consistent with the reference lists: for the uses that are their container's first use,
        the paired notes appear in each list in the same order as the uses appear in the source, also relative to the
        pairs already accepted earlier in this alignment (``self._last_rank``, updated only when the segment agrees)."""
        last = dict(self._last_rank)
        for u, r in zip(src, ren, strict=True):
            if u.container_id is None or self._first_use.get(u.container_id) != u.start:
                continue
            rank = self._note_rank.get(r.target_note or "")
            if rank is None or r.target_note in self._duplicate_notes:
                continue
            if rank[1] <= last.get(rank[0], -1):
                return False
            last[rank[0]] = rank[1]
        self._last_rank = last
        return True

    def _align_segment(self, src: Sequence[Use], ren: Sequence[RenderUse], where: str) -> None:
        if (
            len(src) == len(ren)
            and all(_compatible(a, b) for a, b in zip(src, ren, strict=True))
            and self._numbering_agrees(src, ren)
        ):
            for a, b in zip(src, ren, strict=True):
                self._pair(a, b, "name_anchor" if len(src) == 1 and src[0].name else "position_between_anchors")
            if src:
                self.out.segments[f"{where}:matched"] += 1
            return
        src = self._content_pair(src, ren)
        if not src:
            self.out.segments[f"{where}:content_matched"] += 1
            return
        self.out.segments[f"{where}:abstained"] += 1
        for a in src:
            self.out.use_state[a.id] = "abstained"
        if src:
            self.out.issues.append(
                Issue(
                    "RECONCILIATION_ABSTAINED",
                    tuple(a.id for a in src),
                    f"{where}: {len(src)} source uses, {len(ren)} render uses, no unambiguous pairing",
                )
            )

    def _align(self, src: list[Use], ren: list[RenderUse], where: str) -> None:
        """Anchored alignment: anchors are the k-th use of a name that occurs equally often on both sides."""
        self._last_rank = {}
        s_count = Counter(_key(u) for u in src if _key(u) is not None)
        r_count: Counter[tuple[str, str]] = Counter()
        for r in ren:
            if r.name:
                r_count[(html.unescape(r.group).strip(), html.unescape(r.name).strip())] += 1
        anchor_keys = {k for k, n in s_count.items() if k is not None and r_count.get(k) == n}
        s_anchor: list[tuple[int, int]] = []  # (src position, ren position)
        s_seen: Counter[tuple[str, str]] = Counter()
        r_positions: dict[tuple[str, str], list[int]] = {}
        for j, r in enumerate(ren):
            if r.name:
                rk = (html.unescape(r.group).strip(), html.unescape(r.name).strip())
                if rk in anchor_keys:
                    r_positions.setdefault(rk, []).append(j)
        for i, u in enumerate(src):
            k = _key(u)
            if k is None or k not in anchor_keys:
                continue
            s_anchor.append((i, r_positions[k][s_seen[k]]))
            s_seen[k] += 1
        # Anchors must be increasing on both sides; drop any that cross (the longest increasing chain is kept).
        chain = _longest_increasing(s_anchor)
        prev_i, prev_j = -1, -1
        for i, j in chain:
            self._align_segment(src[prev_i + 1 : i], ren[prev_j + 1 : j], where)
            self._align_segment([src[i]], [ren[j]], where)
            prev_i, prev_j = i, j
        self._align_segment(src[prev_i + 1 :], ren[prev_j + 1 :], where)

    def _align_unordered(self, src: list[Use], ren: list[RenderUse]) -> None:
        """Uses inside one template's output: the template decides the order (an infobox renders its parameters in
        its own order), so names pair regardless of position. Anonymous uses pair only when each side has exactly
        one left."""
        r_by_key: dict[tuple[str, str], list[RenderUse]] = {}
        r_anon: list[RenderUse] = []
        for r in ren:
            name = html.unescape(r.name).strip() if r.name else ""
            if name:
                r_by_key.setdefault((html.unescape(r.group).strip(), name), []).append(r)
            else:
                r_anon.append(r)
        s_by_key: dict[tuple[str, str], list[Use]] = {}
        s_anon: list[Use] = []
        for u in src:
            k = _key(u)
            if k is None:
                s_anon.append(u)
            else:
                s_by_key.setdefault(k, []).append(u)
        if len(src) == 1 and len(ren) == 1 and _compatible(src[0], ren[0]):
            self._pair(src[0], ren[0], "single_use_in_template_output")
            self.out.segments["template:matched"] += 1
            return
        left: list[Use] = []
        for k, uses in s_by_key.items():
            rs = r_by_key.get(k, [])
            if len(rs) == len(uses) and all(_compatible(a, b) for a, b in zip(uses, rs, strict=True)):
                for a, b in zip(uses, rs, strict=True):
                    self._pair(a, b, "name_in_template_output")
            else:
                left.extend(uses)
        if len(s_anon) == 1 and len(r_anon) == 1 and _compatible(s_anon[0], r_anon[0]):
            self._pair(s_anon[0], r_anon[0], "single_anonymous_in_template_output")
        else:
            left.extend(s_anon)
        left = self._content_pair(left, ren)
        if left:
            self.out.segments["template:abstained"] += 1
            for a in left:
                self.out.use_state[a.id] = "abstained"
            self.out.issues.append(
                Issue(
                    "RECONCILIATION_ABSTAINED",
                    tuple(a.id for a in sorted(left, key=lambda u: u.id)),
                    f"template output: {len(src)} source uses, {len(ren)} render uses, no unambiguous pairing",
                )
            )
        else:
            self.out.segments["template:matched"] += 1

    def _top_template(self, t_index: int | None) -> int | None:
        cur = t_index
        while cur is not None and self.m.templates[cur].parent_template is not None:
            cur = self.m.templates[cur].parent_template
        return cur

    def _generating_template(self, u: Use) -> int | None:
        r = self.m.refs[u.ref]
        for t in self.m.templates.values():
            if t.start == r.start and t.end == r.end and t.kind == "generated_ref":
                return t.index
        return None

    def run(self, text: str) -> Reconciliation:
        self.text = text
        m, r = self.m, self.r
        # Template output first: the source templates outside references, aligned to render template parts.
        self._match_templates(
            [t for t in m.templates.values() if t.ref is None and t.parent_template is None and not t.excluded],
            [t for t in r.transclusions if t.in_note is None],
        )
        prose_src = [u for u in m.uses if u.zone == "prose" and u.origin == "tag"]
        prose_ren = [x for x in r.uses if x.in_transclusion is None and x.in_note is None]
        self._align(prose_src, prose_ren, "prose")

        # Uses produced inside template output, grouped by the top-level source template.
        by_template: dict[int, list[Use]] = {}
        for u in m.uses:
            if u.zone == "nested":
                continue
            if u.zone == "prose" and u.origin == "tag":
                continue
            start = self._generating_template(u) if u.origin != "tag" else u.template
            top = self._top_template(start)
            if top is None:
                self.out.use_state[u.id] = "abstained"
                self.out.issues.append(Issue("RECONCILIATION_ABSTAINED", (u.id,), "no enclosing template found"))
                continue
            by_template.setdefault(top, []).append(u)
        ren_by_about: dict[str, list[RenderUse]] = {}
        for x in r.uses:
            if x.in_transclusion is not None and x.in_note is None:
                ren_by_about.setdefault(x.in_transclusion, []).append(x)
        for top, uses in sorted(by_template.items(), key=lambda kv: m.templates[kv[0]].start):
            uses.sort(key=lambda u: (u.start, u.position))
            about = self.out.template_about.get(top)
            if about is None:
                for u in uses:
                    self.out.use_state[u.id] = "abstained"
                self.out.issues.append(
                    Issue("RECONCILIATION_ABSTAINED", tuple(u.id for u in uses), "template output not identified")
                )
                continue
            self._align_unordered(uses, ren_by_about.get(about[0], []))

        # Containers from matched uses (needed before nested uses, whose parent is a container).
        self._containers()

        nested_by_parent: dict[str, list[Use]] = {}
        for u in m.uses:
            if u.zone != "nested":
                continue
            parent = m.ref_container.get(u.parent_ref) if u.parent_ref is not None else None
            if parent is None:
                self.out.use_state[u.id] = "abstained"
                continue
            nested_by_parent.setdefault(parent, []).append(u)
        ren_by_note: dict[str, list[RenderUse]] = {}
        for x in r.uses:
            if x.in_note is not None:
                ren_by_note.setdefault(x.in_note, []).append(x)
        for parent, uses in nested_by_parent.items():
            note = self.out.container_note.get(parent)
            container = self._container_by_id[parent]
            if note is None or len(container.definitions) > 1:
                for u in uses:
                    self.out.use_state[u.id] = "abstained"
                self.out.issues.append(
                    Issue("RECONCILIATION_ABSTAINED", tuple(u.id for u in uses), "parent reference not matched")
                )
                continue
            self._align(sorted(uses, key=lambda u: (u.start, u.position)), ren_by_note.get(note, []), "nested")
        self._containers()  # containers that only nested uses point to

        for u in m.uses:
            self.out.use_state.setdefault(u.id, "abstained")
        self.out.unmatched_render_uses = [x.index for x in r.uses if x.index not in self.out.render_use_matched]
        # An unpaired source use is source_only when no unpaired render use could be its counterpart (none left, or
        # none whose name and group agree); otherwise the pairing was ambiguous and it stays abstained.
        left = [r.uses[i] for i in self.out.unmatched_render_uses]
        for u in m.uses:
            if self.out.use_state[u.id] == "abstained" and not any(not x.data_mw_ok or _compatible(u, x) for x in left):
                self.out.use_state[u.id] = "source_only"
        for idx in self.out.unmatched_render_uses:
            self.out.issues.append(Issue("RENDER_USE_UNMATCHED", (f"render-use-{idx}",)))
        self._bibliography()
        self._units()
        self._witnesses()
        return self.out

    # Templates ----------------------------------------------------------------------------------------------

    def _match_templates(self, src: list[TemplateRecord], ren: list[RenderTransclusion]) -> dict[int, tuple[str, int]]:
        src = sorted(src, key=lambda t: t.start)
        s_keys = [source_template_key(t, self.text, self.wiki) for t in src]
        r_items: list[tuple[str, int, TemplateKey]] = []
        for tr in ren:
            for part, (target, params) in enumerate(tr.templates):
                r_items.append((tr.about, part, render_template_key(target, params, self.wiki)))
        found: dict[int, tuple[str, int]] = {}
        j = 0
        for t, k in zip(src, s_keys, strict=True):
            # In order: the next render part with an equal key. A key seen twice is matched in document order.
            for jj in range(j, len(r_items)):
                if r_items[jj][2] == k:
                    found[t.index] = (r_items[jj][0], r_items[jj][1])
                    j = jj + 1
                    break
        self.out.template_about.update(found)
        return found

    # Containers ---------------------------------------------------------------------------------------------

    def _containers(self) -> None:
        notes = {n.note_id: n for n in self.r.notes}
        duplicated = set(self.r.duplicate_ids)
        for c in self.m.containers:
            if c.kind == "bibliography_entry" or c.id in self.out.container_note:
                continue
            targets = set()
            for uid in c.use_ids:
                if uid in self.out.use_match:
                    target = self.r.uses[self.out.use_match[uid]].target_note
                    if target is not None:
                        targets.add(target)
            if len(targets) == 1:
                note = targets.pop()
                if note in duplicated:
                    # Several elements carry this id: which one is the note cannot be settled by the id.
                    self.out.container_state[c.id] = "note_ambiguous"
                    self.out.issues.append(Issue("RENDER_NOTE_AMBIGUOUS", (c.id,), f"{note} is not a unique id"))
                elif note in notes:
                    self.out.container_note[c.id] = note
                    self.out.container_state[c.id] = "matched"
                    matched = {
                        self.r.uses[self.out.use_match[u]].locator.element_id
                        for u in c.use_ids
                        if u in self.out.use_match
                    }
                    back = set(notes[note].backlinks)
                    if back and not matched <= back:
                        self.out.issues.append(Issue("RENDER_BACKLINK_MISMATCH", (c.id,), note))
                else:
                    self.out.container_state[c.id] = "note_missing"
                    self.out.issues.append(Issue("RENDER_TARGET_MISSING", (c.id,), note))
            elif len(targets) > 1:
                self.out.container_state[c.id] = "conflicting_notes"
                self.out.issues.append(Issue("RENDER_CONTAINER_CONFLICT", (c.id,), ",".join(sorted(targets))))
            else:
                self.out.container_state[c.id] = "unmatched"
        # One rendered note can show only one reference: a note claimed by two containers is withdrawn from both.
        claims = Counter(self.out.container_note.values())
        for cid, note in list(self.out.container_note.items()):
            if claims[note] > 1:
                del self.out.container_note[cid]
                self.out.container_state[cid] = "note_ambiguous"
                self.out.issues.append(Issue("RENDER_NOTE_AMBIGUOUS", (cid,), f"{note} is claimed by {claims[note]}"))

    def _bibliography(self) -> None:
        """A bibliography entry is matched to the render list item that holds the output of its templates."""
        by_about = {t.about: t for t in self.r.transclusions}
        for c in self.m.containers:
            if c.kind != "bibliography_entry":
                continue
            items = set()
            for u in self.m.units:
                if u.container_id != c.id or u.template is None:
                    continue
                about = self.out.template_about.get(u.template)
                if about is not None and about[0] in by_about:
                    items.add(by_about[about[0]].in_list_item or f"about:{about[0]}")
            if not items:
                # No template output: an identifier URL of the entry whose exact href is a link in one list item.
                hrefs = {
                    o.cand.decoded.strip()
                    for o in self.m.occurrences
                    if o.container_id == c.id and o.cand.origin == "url"
                }
                items = {
                    x.in_list_item
                    for x in self.r.links
                    if x.in_list_item is not None and x.in_note is None and x.href in hrefs
                }
            if len(items) == 1:
                self.out.container_note[c.id] = items.pop()
                self.out.container_state[c.id] = "matched"
            elif items:
                self.out.container_state[c.id] = "conflicting_notes"
                self.out.issues.append(Issue("RENDER_CONTAINER_CONFLICT", (c.id,), f"{len(items)} list items"))
            else:
                self.out.container_state[c.id] = "unmatched"

    # Units --------------------------------------------------------------------------------------------------

    def _units(self) -> None:
        trans_by_note: dict[str, list[RenderTransclusion]] = {}
        for t in self.r.transclusions:
            if t.in_note is not None:
                trans_by_note.setdefault(t.in_note, []).append(t)
        for c in self.m.containers:
            note = self.out.container_note.get(c.id)
            units = [u for u in self.m.units if u.container_id == c.id]
            if note is None:
                for u in units:
                    self.out.unit_state[u.id] = "container_unmatched"
                continue
            if c.kind == "bibliography_entry":
                for u in units:
                    if u.template is not None and u.template in self.out.template_about:
                        self.out.unit_transclusion[u.id] = self.out.template_about[u.template][0]
                        self.out.unit_state[u.id] = "matched"
                    elif u.template is None:
                        self.out.unit_state[u.id] = "region_only"
                    else:
                        self.out.unit_state[u.id] = "unmatched"
                continue
            if len(c.definitions) > 1 and c.binding_state == "conflicting_definitions":
                for u in units:
                    self.out.unit_state[u.id] = "conflicting_definitions"
                continue
            first_def = f"{c.id}/d1"
            # A unit's template is matched through its outermost enclosing template inside the ref: the render
            # groups template output by the outermost template only (a cite template wrapped in another template
            # has no transclusion of its own).
            outer = {
                u.id: self._outermost(u.template)
                for u in units
                if u.template is not None and u.definition_id == first_def
            }
            in_note = trans_by_note.get(note, [])
            found = self._match_in_note(sorted(set(outer.values()), key=lambda i: self.m.templates[i].start), in_note)
            for u in units:
                if u.definition_id != first_def:
                    self.out.unit_state[u.id] = "duplicate_definition"
                elif u.template is None or not in_note:
                    # Unstructured text, or a note whose text came out of another template's expansion (a ref in an
                    # infobox parameter): the render marks no template output inside it; the note is the region.
                    self.out.unit_state[u.id] = "region_only"
                elif outer[u.id] in found:
                    self.out.unit_transclusion[u.id] = found[outer[u.id]]
                    self.out.unit_state[u.id] = "matched" if outer[u.id] == u.template else "within_matched_template"
                else:
                    self.out.unit_state[u.id] = "unmatched"

    def _outermost(self, index: int) -> int:
        """The outermost template enclosing ``index`` within the same ref (``index`` itself when it is outermost)."""
        t = self.m.templates[index]
        while t.parent_template is not None and t.parent_template in self.m.templates:
            parent = self.m.templates[t.parent_template]
            if parent.ref != t.ref:
                break
            t = parent
        return t.index

    def _match_in_note(self, templates: list[int], trans: list[RenderTransclusion]) -> dict[int, str]:
        """Template index -> about of the render transclusion with the same canonical target and parameters, in
        document order (each render item is used once)."""
        r_items = [(t.about, render_template_key(tg, p, self.wiki)) for t in trans for tg, p in t.templates]
        found: dict[int, str] = {}
        j = 0
        for index in templates:
            k = source_template_key(self.m.templates[index], self.text, self.wiki)
            for jj in range(j, len(r_items)):
                if r_items[jj][1] == k:
                    found[index] = r_items[jj][0]
                    j = jj + 1
                    break
        return found

    # Identifier witnesses -----------------------------------------------------------------------------------

    def _region_links(self, container_id: str, unit_id: str | None) -> list[RenderLink] | None:
        note = self.out.container_note.get(container_id)
        if note is None:
            return None
        c = self._container_by_id[container_id]
        if c.kind == "bibliography_entry":
            if note.startswith("about:"):
                return list(self._links_by.get(("about", note[6:]), []))
            return list(self._links_by.get(("item", note), []))
        links = list(self._links_by.get(("note", note), []))
        if unit_id is not None and unit_id in self.out.unit_transclusion:
            about = self.out.unit_transclusion[unit_id]
            return [x for x in links if x.in_transclusion == about]
        return links

    def _region_omitted(self, container_id: str, unit_id: str | None) -> bool:
        if unit_id is not None and unit_id in self.out.unit_transclusion:
            return self.out.unit_transclusion[unit_id] in self.omitted
        note = self.out.container_note.get(container_id)
        return note is not None and note in self.omitted_notes

    def _witnesses(self) -> None:
        explained: set[int] = set()
        decoded_cache: dict[int, tuple[str, str | None] | None] = {}

        def link_value(link: RenderLink) -> tuple[str, str | None] | None:
            if link.index not in decoded_cache:
                got = decode_render_href(link.href)
                decoded_cache[link.index] = None if got is None else (got[0], got[1].normalized.normalized)
            return decoded_cache[link.index]

        for o in self.m.occurrences:
            if o.container_id is None:
                self.out.witness_state[o.id] = "outside_reference_container"
                continue
            if o.decoded is None or not o.decoded.normalized.valid:
                self.out.witness_state[o.id] = "not_comparable"
                continue
            unit = o.unit_id if o.role != "marker_target" else None
            links = self._region_links(o.container_id, unit)
            if links is None:
                self.out.witness_state[o.id] = "region_not_reconciled"
                continue
            hits = [x.index for x in links if link_value(x) == (o.cand.scheme, o.decoded.normalized.normalized)]
            self.out.witnesses[o.id] = hits
            explained.update(hits)
            if hits:
                self.out.witness_state[o.id] = "render_link_found"
            elif self._region_omitted(o.container_id, unit):
                # MediaWiki stopped expanding templates here (a parser limit): absence says nothing.
                self.out.witness_state[o.id] = "render_template_omitted"
            else:
                self.out.witness_state[o.id] = "no_render_link_in_region"
        reconciled = set(self.out.container_note.values())
        for link in self.r.links:
            value = link_value(link)
            if value is None or link.index in explained:
                continue
            if link.in_note is None and link.in_list_item is None:
                continue
            region = link.in_note if link.in_note is not None else link.in_list_item
            in_reconciled = region in reconciled or (
                link.in_transclusion is not None and f"about:{link.in_transclusion}" in reconciled
            )
            self.out.render_only_links.append(
                {
                    "render_link": link.index,
                    "scheme": value[0],
                    "normalized": value[1],
                    "note": link.in_note,
                    "list_item": link.in_list_item,
                    "transclusion": link.in_transclusion,
                    "hidden": link.hidden,
                    "region_reconciled": in_reconciled,
                }
            )
            if in_reconciled:
                self.out.issues.append(
                    Issue("RENDER_ONLY_IDENTIFIER", (f"render-link-{link.index}",), f"{value[0]} {value[1]}")
                )


def _longest_increasing(pairs: list[tuple[int, int]]) -> list[tuple[int, int]]:
    """Longest chain of pairs increasing in both coordinates (pairs are sorted by the first), O(n log n)."""
    tails: list[int] = []
    tails_idx: list[int] = []
    prev = [-1] * len(pairs)
    for k, (_, j) in enumerate(pairs):
        pos = bisect.bisect_left(tails, j)
        if pos == len(tails):
            tails.append(j)
            tails_idx.append(k)
        else:
            tails[pos] = j
            tails_idx[pos] = k
        prev[k] = tails_idx[pos - 1] if pos > 0 else -1
    out = []
    k = tails_idx[-1] if tails_idx else -1
    while k >= 0:
        out.append(pairs[k])
        k = prev[k]
    return out[::-1]


def reconcile(model: SourceModel, render: RenderDoc, wiki: WikiProfile, profile: Profile, text: str) -> Reconciliation:
    return Reconciler(model, render, wiki, profile).run(text)
